"""Research Agent for Multi-Agent Workflow.

Responsible for reasoning through the generated plan steps, producing structured
findings, identifying explicit assumptions, and highlighting open questions.
Persists execution step lifecycle in PostgreSQL when run_id is provided.
"""

from typing import Any, Dict
from langchain_core.messages import SystemMessage, HumanMessage

from backend.app.core.logging import format_log_msg, get_logger
from backend.app.db.session import get_db_context
from backend.app.graph.state import WorkflowState
from backend.app.models.schemas import ResearchResult
from backend.app.services.llm import get_llm, invoke_structured
from backend.app.services.workflow_runs import complete_workflow_step, create_workflow_step, fail_workflow_step

logger = get_logger(__name__)

RESEARCHER_SYSTEM_PROMPT = """You are an expert Research & Reasoning Agent in a Multi-Agent AI system.
Your job is to execute the strategic plan generated by the Planner Agent.

Guidelines:
- Analyze the user query in conjunction with each step in the provided plan.
- Produce concrete, detailed findings addressing each step.
- Explicitly separate confirmed analytical findings from assumptions.
- Highlight any unanswered questions or unknowns that need further exploration.
- Maintain objectivity, technical depth, and actionable clarity.
"""


async def research_agent(state: WorkflowState) -> Dict[str, Any]:
    """Execute the Research Agent node.

    Args:
        state: Current WorkflowState.

    Returns:
        State update dictionary containing research_results and intermediate step.
    """
    request_id = state.get("request_id", "unknown")
    run_id = state.get("run_id")
    user_query = state.get("user_query", "")
    plan_data = state.get("plan")
    retrieved_docs = state.get("retrieved_documents") or []

    logger.info(format_log_msg(f"Research agent started (run_id: {run_id or 'none'})", request_id))

    step_id = None
    if run_id:
        try:
            async with get_db_context() as session:
                step = await create_workflow_step(
                    session=session,
                    run_id=run_id,
                    agent_name="researcher",
                    step_order=3,
                    input_data={"plan": plan_data, "retrieved_chunks_count": len(retrieved_docs)},
                )
                step_id = step.id
        except Exception as db_err:
            logger.warning(format_log_msg(f"Could not persist researcher step start: {db_err}", request_id))

    # Guard against previous critical errors or missing plan
    if not plan_data:
        err_msg = "Research Agent cannot proceed: No execution plan found in state."
        logger.error(format_log_msg(err_msg, request_id))

        if step_id:
            try:
                async with get_db_context() as session:
                    await fail_workflow_step(session=session, step_id=step_id, error_message=err_msg)
            except Exception as db_err:
                logger.warning(format_log_msg(f"Could not persist researcher step failure: {db_err}", request_id))

        return {
            "errors": [err_msg],
            "intermediate_results": [{"agent": "researcher", "error": err_msg}],
        }

    try:
        llm = get_llm()
        goal = plan_data.get("goal", "")
        steps = plan_data.get("steps", [])

        plan_summary = f"Goal: {goal}\nSteps:\n" + "\n".join(f"{idx+1}. {step}" for idx, step in enumerate(steps))

        retrieved_context = ""
        if retrieved_docs:
            chunks_formatted = "\n---\n".join(
                f"[Document: {doc.get('metadata', {}).get('filename') or doc.get('filename', 'Unknown')} | Page {doc.get('metadata', {}).get('page_number') or doc.get('page_number', '1')}]\n{doc.get('content') or doc.get('text', '')}"
                for doc in retrieved_docs
            )
            retrieved_context = f"\n\nRetrieved Relevant Document Passages:\n{chunks_formatted}"

        prompt_content = (
            f"User Query:\n{user_query}\n\n"
            f"Strategic Plan to Research:\n{plan_summary}"
            f"{retrieved_context}\n\n"
            f"Perform structured reasoning across the planned steps, integrating any retrieved document evidence, and deliver comprehensive research results."
        )

        messages = [
            SystemMessage(content=RESEARCHER_SYSTEM_PROMPT),
            HumanMessage(content=prompt_content),
        ]

        # Produce validated structured output
        research_result: ResearchResult = await invoke_structured(llm, messages, ResearchResult)
        research_dict = research_result.model_dump()

        if step_id:
            try:
                async with get_db_context() as session:
                    await complete_workflow_step(session=session, step_id=step_id, output_data=research_dict)
            except Exception as db_err:
                logger.warning(format_log_msg(f"Could not persist researcher step completion: {db_err}", request_id))

        logger.info(
            format_log_msg(
                f"Researcher completed with {len(research_result.findings)} findings, "
                f"{len(research_result.assumptions)} assumptions, and "
                f"{len(research_result.unanswered_questions)} open questions.",
                request_id,
            )
        )

        return {
            "research_results": research_dict,
            "intermediate_results": [
                {
                    "agent": "researcher",
                    "output": research_dict,
                }
            ],
        }

    except Exception as exc:
        err_msg = f"Research Agent failed: {str(exc)}"
        logger.error(format_log_msg(err_msg, request_id))

        if step_id:
            try:
                async with get_db_context() as session:
                    await fail_workflow_step(session=session, step_id=step_id, error_message=err_msg)
            except Exception as db_err:
                logger.warning(format_log_msg(f"Could not persist researcher step failure: {db_err}", request_id))

        return {
            "errors": [err_msg],
            "intermediate_results": [{"agent": "researcher", "error": err_msg}],
        }
